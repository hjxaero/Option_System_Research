from __future__ import annotations

import argparse
import sys
from concurrent.futures import ProcessPoolExecutor, as_completed
from pathlib import Path

import pandas as pd

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from option_platform.common.settings import PlatformPaths
from option_platform.data.live_update import update_symbol_range_minute_quotes
from option_platform.data.quality.minute_quote_report import write_quality_report
from option_platform.data.sources.tq import tq_api


def parse_args() -> argparse.Namespace:
    parser = argparse.ArgumentParser(description="Repair minute quote parquet files from a repair plan CSV.")
    parser.add_argument("--plan", required=True, help="Repair plan CSV generated by generate_repair_plan.py")
    parser.add_argument("--product", default="MO")
    parser.add_argument("--workers", type=int, default=6)
    parser.add_argument("--max-quote-age-ms", type=int, default=60_000)
    parser.add_argument("--reason", action="append", help="Only repair rows whose reason contains this token.")
    parser.add_argument("--max-repairs", type=int, default=0, help="Debug limit by symbol-day rows. 0 means all.")
    parser.add_argument("--report-prefix", help="Quality report prefix after repair.")
    parser.add_argument("--output-dir", help="Quality report directory after repair.")
    parser.add_argument("--dry-run", action="store_true")
    return parser.parse_args()


def _load_plan(plan_path: Path, reason_tokens: list[str] | None, max_repairs: int) -> pd.DataFrame:
    plan = pd.read_csv(plan_path)
    required = {"date", "symbol", "reason"}
    missing = required - set(plan.columns)
    if missing:
        raise ValueError(f"repair plan missing columns: {sorted(missing)}")

    plan = plan.copy()
    plan["date"] = plan["date"].astype(str)
    plan["symbol"] = plan["symbol"].astype(str)
    plan["reason"] = plan["reason"].astype(str)

    if reason_tokens:
        mask = pd.Series(False, index=plan.index)
        for token in reason_tokens:
            mask |= plan["reason"].str.contains(token, regex=False)
        plan = plan.loc[mask].copy()

    plan = plan.sort_values(["date", "symbol"]).drop_duplicates(["date", "symbol"])
    if max_repairs > 0:
        plan = plan.head(max_repairs).copy()
    return plan


def _build_jobs(plan: pd.DataFrame, data_root: Path, product: str, max_quote_age_ms: int) -> list[dict]:
    jobs = []
    for symbol, group in plan.groupby("symbol", sort=True):
        jobs.append(
            {
                "symbol": symbol,
                "trade_dates": sorted(group["date"].unique().tolist()),
                "data_root": str(data_root),
                "product": product.upper(),
                "max_quote_age_ms": max_quote_age_ms,
            }
        )
    return jobs


def _repair_symbol_job(payload: dict) -> dict:
    symbol = payload["symbol"]
    try:
        with tq_api() as api:
            saved, skipped, failures = update_symbol_range_minute_quotes(
                api=api,
                data_root=payload["data_root"],
                product=payload["product"],
                symbol=symbol,
                trade_dates=payload["trade_dates"],
                max_quote_age_ms=payload["max_quote_age_ms"],
                skip_if_complete=False,
            )
        return {
            "symbol": symbol,
            "saved": saved,
            "skipped": skipped,
            "failures": failures,
            "error": None,
        }
    except Exception as exc:
        return {
            "symbol": symbol,
            "saved": 0,
            "skipped": 0,
            "failures": [],
            "error": str(exc),
        }


def _load_repaired_range(data_root: Path, product: str, dates: list[str]) -> pd.DataFrame:
    root = data_root / "quotes" / "minute" / product.upper()
    if not root.exists():
        return pd.DataFrame()
    date_set = set(dates)
    frames = [
        pd.read_parquet(path)
        for path in sorted(root.glob("*/*.parquet"))
        if path.stem in date_set
    ]
    return pd.concat(frames, ignore_index=True) if frames else pd.DataFrame()


def main() -> None:
    args = parse_args()
    paths = PlatformPaths.from_root(PROJECT_ROOT)
    plan_path = Path(args.plan)
    plan = _load_plan(plan_path, args.reason, args.max_repairs)
    jobs = _build_jobs(plan, paths.data_root, args.product, args.max_quote_age_ms)
    symbol_days = sum(len(job["trade_dates"]) for job in jobs)
    dates = sorted(plan["date"].unique().tolist()) if not plan.empty else []

    print(
        f"plan_rows={len(plan)} symbols={len(jobs)} symbol_days={symbol_days} "
        f"workers={args.workers} dry_run={args.dry_run}",
        flush=True,
    )
    if args.dry_run:
        for job in jobs[:10]:
            print(f"[dry-run] {job['symbol']} dates={','.join(job['trade_dates'])}", flush=True)
        return

    saved_total = 0
    skipped_total = 0
    failed_symbols = 0
    total = len(jobs)

    if args.workers <= 1:
        for idx, job in enumerate(jobs, 1):
            print(f"[{idx}/{total}] repair {job['symbol']} days={len(job['trade_dates'])}", flush=True)
            result = _repair_symbol_job(job)
            saved_total += result["saved"]
            skipped_total += result["skipped"]
            if result["error"] or result["failures"]:
                failed_symbols += 1
                print(f"  fail {result['error'] or result['failures'][:3]}", flush=True)
    else:
        with ProcessPoolExecutor(max_workers=args.workers) as pool:
            futures = {pool.submit(_repair_symbol_job, job): job["symbol"] for job in jobs}
            done = 0
            for future in as_completed(futures):
                done += 1
                result = future.result()
                saved_total += result["saved"]
                skipped_total += result["skipped"]
                if result["error"] or result["failures"]:
                    failed_symbols += 1
                    print(
                        f"[{done}/{total}] fail {result['symbol']}: "
                        f"{result['error'] or result['failures'][:3]}",
                        flush=True,
                    )
                else:
                    print(
                        f"[{done}/{total}] {result['symbol']} "
                        f"saved={result['saved']} skipped={result['skipped']}",
                        flush=True,
                    )

    print(
        f"done saved_days={saved_total} skipped_days={skipped_total} failed_symbols={failed_symbols}",
        flush=True,
    )

    if dates:
        report_dir = (
            Path(args.output_dir)
            if args.output_dir
            else paths.data_root / "quality" / args.product.upper() / "repair"
        )
        prefix = args.report_prefix or (
            f"{args.product.upper()}_{dates[0].replace('-', '')}_{dates[-1].replace('-', '')}_after_repair"
        )
        all_quotes = _load_repaired_range(paths.data_root, args.product, dates)
        summary_path, by_symbol_path = write_quality_report(all_quotes, report_dir, prefix)
        print(f"rows={len(all_quotes)} summary={summary_path} by_symbol={by_symbol_path}", flush=True)


if __name__ == "__main__":
    main()
